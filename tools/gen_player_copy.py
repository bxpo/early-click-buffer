#!/usr/bin/env python3
"""
Generates src/PlayerCopy.inc: assignment statements that copy every plain-data
physics field of PlayerObject from `src` to `dst`, read from a Geode bindings
.bro file. Owned objects (sprites, particles, arrays, layers) are skipped so the
ghost player never shares ownership of anything with the real one.

usage: gen_player_copy.py <bindings>/bindings/2.2081/GeometryDash.bro > src/PlayerCopy.inc
"""
import re
import sys

VALUE_TYPES = {
    "bool", "int", "float", "double", "unsigned char", "unsigned int",
    "cocos2d::CCPoint", "geode::SeedValueRSV",
}
VALUE_PREFIXES = ("gd::unordered_set<int>", "gd::unordered_map<int,", "gd::map<int, bool>", "gd::vector<float>")
# Raw pointers into the level (not owned by the player): safe to share.
LEVEL_POINTERS = {"GameObject*", "DashRingObject*"}
# Cosmetic or ownership-related fields we deliberately leave alone.
DENY = {
    "m_isHidden", "m_hasGlow", "m_playEffects", "m_iconRequestID",
    "m_maybeIsVehicleGlowing", "m_switchWaveTrailColor", "m_practiceDeathEffect",
    "m_flashTime", "m_flashDuration", "m_flashDelay", "m_useLandParticles0",
    "m_landParticlesAngle", "m_landParticleRelatedY", "m_playerStreak",
    "m_streakStrokeWidth", "m_disableStreakTint", "m_alwaysShowStreak",
    "m_fadeOutStreak", "m_hasCustomGlowColor", "m_defaultMiniIcon", "m_swapColors",
    "m_switchDashFireColor", "m_justPlacedStreak", "m_audioScale",
    "m_shouldTryPlacingCheckpoint", "m_canPlaceCheckpoint", "m_onFlyCheckpointTries",
    "m_lastCheckpointTime", "m_checkpointTimeout", "m_trailingParticleLife",
}


def main(path: str) -> None:
    text = open(path, encoding="utf-8").read()
    start = text.index("class PlayerObject : GameObject")
    end = text.index("\n}", start)
    body = text[start:end].splitlines()[1:]

    out = [
        "// Generated by tools/gen_player_copy.py from Geode bindings (GD 2.2081). Do not edit.",
        "// Expects `PlayerObject* dst` and `PlayerObject* src` in scope.",
    ]
    depth = 0
    for raw in body:
        line = raw.strip()
        if line.endswith("{") and "(" not in line:  # platform-specific block, e.g. "android, ios {"
            depth += 1
            continue
        if line == "}":
            depth = max(0, depth - 1)
            continue
        if depth or not line.endswith(";") or "(" in line or "=" in line or line.startswith("//"):
            continue
        m = re.match(r"^(.+?)\s*(\*?)\s*(m_\w+|unk_\w+);$", line)
        if not m:
            continue
        typ = (m.group(1) + m.group(2)).replace(" *", "*").strip()
        name = m.group(3)
        if name in DENY:
            continue
        ok = typ in VALUE_TYPES or typ in LEVEL_POINTERS or typ.startswith(VALUE_PREFIXES)
        if ok:
            out.append(f"dst->{name} = src->{name};")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
